import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

import Ajv2020 from "ajv/dist/2020.js";
import standaloneCode from "ajv/dist/standalone/index.js";

import channelStateSchema from "../schemas/channel-state.schema.json" with { type: "json" };
import kaspaBatchExtraSchema from "../schemas/kaspa-batch-extra.schema.json" with { type: "json" };
import kaspaPaymentPayloadSchema from "../schemas/kaspa-payment-payload.schema.json" with { type: "json" };
import kaspaRequirementsExtraSchema from "../schemas/kaspa-requirements-extra.schema.json" with { type: "json" };
import paymentIdentifierSchema from "../schemas/payment-identifier.schema.json" with { type: "json" };
import paymentPayloadSchema from "../schemas/payment-payload.schema.json" with { type: "json" };
import paymentRequiredSchema from "../schemas/payment-required.schema.json" with { type: "json" };
import settlementResponseSchema from "../schemas/settlement-response.schema.json" with { type: "json" };

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const OUT_DIR = path.join(ROOT, "packages/core/src/generated");
const OUT_JS = path.join(OUT_DIR, "schema-validators.js");
const OUT_DTS = path.join(OUT_DIR, "schema-validators.d.ts");

const SCHEMA_IDS = {
  channelState: "https://kaspa-x402.org/schemas/channel-state.schema.json",
  kaspaBatchExtra: "https://kaspa-x402.org/schemas/kaspa-batch-extra.schema.json",
  kaspaPaymentPayload: "https://kaspa-x402.org/schemas/kaspa-payment-payload.schema.json",
  kaspaRequirementsExtra: "https://kaspa-x402.org/schemas/kaspa-requirements-extra.schema.json",
  paymentIdentifier: "https://kaspa-x402.org/schemas/payment-identifier.schema.json",
  paymentPayload: "https://kaspa-x402.org/schemas/payment-payload.schema.json",
  paymentRequired: "https://kaspa-x402.org/schemas/payment-required.schema.json",
  settlementResponse: "https://kaspa-x402.org/schemas/settlement-response.schema.json",
};

const PAYMENT_REQUIREMENTS_ENTRY_SCHEMA_ID = "https://kaspa-x402.org/schemas/internal/payment-requirements-entry.schema.json";
const VALIDATOR_EXPORTS = {
  validateChannelState: SCHEMA_IDS.channelState,
  validateKaspaBatchExtra: SCHEMA_IDS.kaspaBatchExtra,
  validateKaspaPaymentPayload: SCHEMA_IDS.kaspaPaymentPayload,
  validateKaspaRequirementsExtra: SCHEMA_IDS.kaspaRequirementsExtra,
  validatePaymentIdentifier: SCHEMA_IDS.paymentIdentifier,
  validatePaymentPayload: SCHEMA_IDS.paymentPayload,
  validatePaymentRequired: SCHEMA_IDS.paymentRequired,
  validateSettlementResponse: SCHEMA_IDS.settlementResponse,
  validatePaymentRequirementsEntry: PAYMENT_REQUIREMENTS_ENTRY_SCHEMA_ID,
};

const ajv = new Ajv2020({
  allErrors: true,
  strict: false,
  code: {
    esm: true,
    source: true,
  },
});

for (const schema of [
  channelStateSchema,
  kaspaBatchExtraSchema,
  kaspaPaymentPayloadSchema,
  kaspaRequirementsExtraSchema,
  paymentIdentifierSchema,
  paymentPayloadSchema,
  paymentRequiredSchema,
  settlementResponseSchema,
]) {
  ajv.addSchema(schema);
}

ajv.addSchema({
  $id: PAYMENT_REQUIREMENTS_ENTRY_SCHEMA_ID,
  $ref: `${SCHEMA_IDS.paymentRequired}#/$defs/paymentRequirements`,
});

fs.mkdirSync(OUT_DIR, { recursive: true });
const validatorCode = inlineAjvRuntimeHelpers(standaloneCode(ajv, VALIDATOR_EXPORTS));
fs.writeFileSync(
  OUT_JS,
  `// Generated by scripts/generate-schema-validators.mjs. Do not edit by hand.\n${validatorCode}\n`,
);
fs.writeFileSync(
  OUT_DTS,
  `// Generated by scripts/generate-schema-validators.mjs. Do not edit by hand.\n` +
    `import type { ErrorObject } from "ajv";\n\n` +
    `export type StandaloneValidateFunction = ((data: unknown) => boolean) & { errors?: ErrorObject[] | null };\n` +
    Object.keys(VALIDATOR_EXPORTS)
      .map((name) => `export const ${name}: StandaloneValidateFunction;\n`)
      .join(""),
);

console.log(JSON.stringify({ ok: true, files: [path.relative(ROOT, OUT_JS), path.relative(ROOT, OUT_DTS)] }, null, 2));

function inlineAjvRuntimeHelpers(code) {
  return code.replaceAll(
    /const (func\d+) = require\("ajv\/dist\/runtime\/ucs2length"\)\.default;/g,
    `const $1 = function ucs2length(str) {
  let length = 0;
  for (let index = 0; index < str.length; index++, length++) {
    const first = str.charCodeAt(index);
    if (first < 0xd800 || first > 0xdbff || index + 1 >= str.length) continue;
    const second = str.charCodeAt(index + 1);
    if (second >= 0xdc00 && second <= 0xdfff) index++;
  }
  return length;
};`,
  );
}
