#!/usr/bin/env node
import { spawnSync } from "node:child_process";
import crypto from "node:crypto";
import fs from "node:fs";
import os from "node:os";
import path from "node:path";
import { fileURLToPath } from "node:url";

const EXPECTED_COMPILER_COMMIT = "3ed973335b59269293564805cc2c58a14595ec03";
const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const sourceRelative = "contracts/kaspa-x402-hash-chain-head-v2.sil";
const source = path.join(root, sourceRelative);
const fixtureFile = path.join(root, "contracts/fixtures/kaspa-x402-hash-chain-head-v2.json");
const generatedFile = path.join(root, "packages/covenant/src/generated/hash-chain-head-v2.ts");
const silverscriptRoot = path.resolve(
  process.env.SILVERSCRIPT_DIR ?? path.resolve(root, "../silverscript"),
);
const check = process.argv.includes("--check");
if (process.argv.slice(2).some((arg) => arg !== "--check")) throw new Error("usage: generate-hash-chain-fixture.mjs [--check]");

const compilerCommit = run("git", ["rev-parse", "HEAD"], silverscriptRoot).trim();
if (compilerCommit !== EXPECTED_COMPILER_COMMIT) {
  throw new Error(`SilverScript is at ${compilerCommit}; expected ${EXPECTED_COMPILER_COMMIT}`);
}
if (run("git", ["status", "--porcelain", "--", "silverscript-lang", "silverscript-abi"], silverscriptRoot).trim()) {
  throw new Error("SilverScript compiler source has uncommitted changes");
}

// The sample owner is the x-only key for private key 0x09 repeated 32 times.
// It is public fixture material, not an operator or deployment key.
const owner = "56b328b30c8bf5839e24058747879408bdb36241dc9c2e7c619faa12b2920967";
const otherOwner = "f991f944d1e1954a7fc8b9bf62e0d78f015f4c07762d505e20e6c45260a3661b";
const guard = "22".repeat(32);
const otherGuard = "23".repeat(32);
const artifact = compile(owner, guard);
const contract = artifact.contracts.KaspaX402HashChainHeadV2;
if (!contract) throw new Error("silverc did not emit KaspaX402HashChainHeadV2");
const base = Buffer.from(contract.compiled.bytecode);
const ownerOffsets = allOffsets(base, Buffer.from(owner, "hex"));
const stateLayout = contract.compiled.state_span;
const guardOffset = stateLayout.offset + 1;
if (stateLayout.len !== 33 || base[guardOffset - 1] !== 32 || ownerOffsets.length === 0) {
  throw new Error("unexpected SilverScript owner or guard layout");
}
assertVariant(compile(owner, otherGuard), [[guardOffset, Buffer.from(guard, "hex"), Buffer.from(otherGuard, "hex")]], true);
assertVariant(compile(otherOwner, guard), ownerOffsets.map((offset) => [offset, Buffer.from(owner, "hex"), Buffer.from(otherOwner, "hex")]), false);

const selectors = {
  borrow: contract.entries.borrow.dispatch_tag,
  ownerRotate: contract.entries.ownerRotate.dispatch_tag,
  ownerSweep: contract.entries.ownerSweep.dispatch_tag,
};
const fixture = {
  format: "kaspa-x402-hash-chain-silverc-artifact-v1",
  templateId: "kaspa-x402-hash-chain-head-v2",
  source: sourceRelative,
  sourceSha256: sha256(fs.readFileSync(source)),
  compiler: {
    name: "silverc",
    checkedCommit: compilerCommit,
    compilerVersion: artifact.compiler_version,
    command: "cd <silverscript-checkout> && cargo run --quiet -p silverscript-lang --bin silverc -- <kaspa-x402-root>/contracts/kaspa-x402-hash-chain-head-v2.sil --constructor-args <args.json> -c > <out.json>",
  },
  constructor: { sampleOwnerPublicKey: owner, sampleGuard: guard },
  layout: { guardOffset, stateSpan: stateLayout, ownerOffsets },
  selectors,
  sampleTemplateHash: Buffer.from(contract.compiled.template_hash).toString("hex"),
  compiledBaseSha256: sha256(base),
  artifact,
};
const generated = `// Generated by scripts/generate-hash-chain-fixture.mjs. Do not edit.
export const HASH_CHAIN_HEAD_V2_COMPILED_BASE = ${JSON.stringify(base.toString("hex"))};
export const HASH_CHAIN_HEAD_V2_SAMPLE_OWNER = ${JSON.stringify(owner)};
export const HASH_CHAIN_HEAD_V2_SAMPLE_GUARD = ${JSON.stringify(guard)};
export const HASH_CHAIN_HEAD_V2_LAYOUT = ${JSON.stringify(fixture.layout, null, 2)} as const;
export const HASH_CHAIN_HEAD_V2_SELECTORS = ${JSON.stringify(selectors, null, 2)} as const;
export const HASH_CHAIN_HEAD_V2_SAMPLE_TEMPLATE_HASH = ${JSON.stringify(fixture.sampleTemplateHash)};
export const HASH_CHAIN_HEAD_V2_SOURCE_SHA256 = ${JSON.stringify(fixture.sourceSha256)};
export const HASH_CHAIN_HEAD_V2_COMPILED_BASE_SHA256 = ${JSON.stringify(fixture.compiledBaseSha256)};
export const HASH_CHAIN_HEAD_V2_COMPILER_COMMIT = ${JSON.stringify(compilerCommit)};
`;
writeOrCheck(fixtureFile, `${JSON.stringify(fixture, null, 2)}\n`);
writeOrCheck(generatedFile, generated);
console.log(`${check ? "verified" : "generated"} hash-chain SilverScript artifact (${base.length} bytes, ${compilerCommit.slice(0, 8)})`);

function compile(ownerPublicKey, initialGuard) {
  const dir = fs.mkdtempSync(path.join(os.tmpdir(), "kaspa-x402-hash-chain-ctor-"));
  try {
    const args = path.join(dir, "args.json");
    fs.writeFileSync(args, JSON.stringify([portableBytes(ownerPublicKey), portableBytes(initialGuard)]));
    const result = spawnSync("cargo", ["run", "--quiet", "-p", "silverscript-lang", "--bin", "silverc", "--", source, "--constructor-args", args, "-c"], {
      cwd: silverscriptRoot,
      encoding: "utf8",
    });
    if (result.status !== 0) throw new Error(result.stderr || result.stdout || "silverc failed");
    return JSON.parse(result.stdout);
  } finally {
    fs.rmSync(dir, { recursive: true, force: true });
  }
}

function assertVariant(candidate, patches, expectSameTemplateHash) {
  const expected = Buffer.from(base);
  for (const [offset, oldBytes, newBytes] of patches) {
    if (!expected.subarray(offset, offset + oldBytes.length).equals(oldBytes)) {
      throw new Error(`constructor patch at ${offset} did not match the compiled base`);
    }
    newBytes.copy(expected, offset);
  }
  const actual = Buffer.from(candidate.contracts.KaspaX402HashChainHeadV2.compiled.bytecode);
  if (!expected.equals(actual)) throw new Error("constructor patch does not reproduce silverc bytecode");
  if (expectSameTemplateHash && Buffer.from(candidate.contracts.KaspaX402HashChainHeadV2.compiled.template_hash).toString("hex") !== Buffer.from(contract.compiled.template_hash).toString("hex")) {
    throw new Error("constructor variant changed the SilverScript template hash");
  }
}

function allOffsets(haystack, needle) {
  const offsets = [];
  for (let at = haystack.indexOf(needle); at !== -1; at = haystack.indexOf(needle, at + 1)) offsets.push(at);
  return offsets;
}

function portableBytes(value) {
  return { kind: "bytes", value: [...Buffer.from(value, "hex")] };
}

function sha256(value) {
  return crypto.createHash("sha256").update(value).digest("hex");
}

function run(command, args, cwd) {
  const result = spawnSync(command, args, { cwd, encoding: "utf8" });
  if (result.status !== 0) throw new Error(result.stderr || result.stdout || `${command} failed`);
  return result.stdout;
}

function writeOrCheck(file, content) {
  if (check) {
    if (!fs.existsSync(file) || fs.readFileSync(file, "utf8") !== content) {
      throw new Error(`${path.relative(root, file)} is stale; run npm run generate:hash-chain-fixture`);
    }
  } else {
    fs.mkdirSync(path.dirname(file), { recursive: true });
    fs.writeFileSync(file, content);
  }
}
